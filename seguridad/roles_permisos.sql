
CREATE SCHEMA IF NOT EXISTS dw;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_roles
        WHERE rolname = 'rol_analista'
    ) THEN
        CREATE ROLE rol_analista NOLOGIN;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_roles
        WHERE rolname = 'rol_etl'
    ) THEN
        CREATE ROLE rol_etl NOLOGIN;
    END IF;
END
$$;

GRANT USAGE ON SCHEMA dw TO rol_analista;
GRANT USAGE ON SCHEMA dw TO rol_etl;

GRANT SELECT ON ALL TABLES
IN SCHEMA dw TO rol_analista;

GRANT SELECT, INSERT, UPDATE
ON ALL TABLES IN SCHEMA dw TO rol_etl;

GRANT USAGE, SELECT ON ALL SEQUENCES
IN SCHEMA dw TO rol_etl;

ALTER DEFAULT PRIVILEGES IN SCHEMA dw
GRANT SELECT ON TABLES TO rol_analista;

ALTER DEFAULT PRIVILEGES IN SCHEMA dw
GRANT SELECT, INSERT, UPDATE
ON TABLES TO rol_etl;

ALTER DEFAULT PRIVILEGES IN SCHEMA dw
GRANT USAGE, SELECT ON SEQUENCES TO rol_etl;
